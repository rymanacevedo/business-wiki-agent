import assert from "node:assert/strict";
import { test } from "node:test";
import { diffRuns, rewriteReadmeBlock, type Run } from "../diff";
import type { CaseReport } from "../index";

function row(
  id: string,
  over: Partial<CaseReport> & Pick<CaseReport, "verdict">
): CaseReport {
  return {
    id,
    caseId: id.replaceAll("/", "-"),
    description: null,
    class: "normal",
    tags: ["normal"],
    gates: [],
    scores: {},
    toolCalls: 0,
    costUsd: 0,
    traceIds: [],
    resultsJsonl: null,
    ...over,
  };
}

// Hand-computed expectations below come from these two runs.
const before: Run = {
  label: "before",
  slices: [
    {
      label: "before",
      slice: "ingest",
      cases: [
        row("ingest/sources/0000", {
          verdict: "passed",
          scores: { extraction: 1, page_faithful: 0.8 },
          toolCalls: 10,
          costUsd: 0.01,
        }),
        row("ingest/sources/0001", {
          verdict: "failed",
          class: "trap",
          tags: ["trap"],
          gates: [
            { name: "succeeded", passed: true },
            { name: "satisfies [personal-only]", passed: false },
          ],
          scores: { extraction: 0.5, page_faithful: 0.4 },
          toolCalls: 14,
          costUsd: 0.03,
        }),
      ],
    },
    {
      label: "before",
      slice: "query",
      cases: [
        row("query/0000", { verdict: "scored", toolCalls: 3, costUsd: 0.002 }),
      ],
    },
  ],
};

const after: Run = {
  label: "after",
  slices: [
    {
      label: "after",
      slice: "ingest",
      cases: [
        row("ingest/sources/0000", {
          verdict: "passed",
          scores: { extraction: 1, page_faithful: 1 },
          toolCalls: 8,
          costUsd: 0.01,
        }),
        row("ingest/sources/0001", {
          verdict: "passed",
          class: "trap",
          tags: ["trap"],
          gates: [{ name: "satisfies [personal-only]", passed: true }],
          scores: { extraction: 0.75, page_faithful: 0.6 },
          toolCalls: 12,
          costUsd: 0.02,
        }),
      ],
    },
    {
      label: "after",
      slice: "query",
      cases: [
        row("query/0000", { verdict: "passed", toolCalls: 2, costUsd: 0.001 }),
      ],
    },
  ],
};

test("the README block has one row per slice plus a total", () => {
  const { readmeBlock } = diffRuns(before, after);

  assert.equal(
    readmeBlock,
    [
      "| Slice | Cases | Pass rate before | Pass rate after | Mean tool calls | Cost |",
      "| --- | --- | --- | --- | --- | --- |",
      "| ingest | 2 | 1/2 (50%) | 2/2 (100%) | 12.0 → 10.0 | $0.0400 → $0.0300 |",
      "| query | 1 | 0/1 (0%) | 1/1 (100%) | 3.0 → 2.0 | $0.0020 → $0.0010 |",
      "| **total** | 3 | 1/3 (33%) | 3/3 (100%) | 9.0 → 7.3 | $0.0420 → $0.0310 |",
    ].join("\n")
  );
});

test("the before/after page has pass rates by slice and class, score means, and failed gates per case", () => {
  const { markdown } = diffRuns(before, after);

  assert.match(markdown, /^# Before and after: `before` → `after`/);
  assert.match(markdown, /Generated by `scripts\/eval-diff\.ts before after`/);
  assert.ok(
    markdown.includes("| trap | 1 | 0/1 (0%) | 1/1 (100%) |"),
    markdown
  );
  assert.ok(
    markdown.includes("| normal | 2 | 1/2 (50%) | 2/2 (100%) |"),
    markdown
  );
  assert.ok(
    markdown.includes("| ingest | extraction | 0.75 | 0.88 |"),
    markdown
  );
  assert.ok(
    markdown.includes("| ingest | page_faithful | 0.60 | 0.80 |"),
    markdown
  );
  assert.ok(
    markdown.includes(
      "| ingest/sources/0001 | satisfies [personal-only] | none |"
    ),
    markdown
  );
  assert.ok(
    !markdown.includes("| ingest/sources/0000 |"),
    "passing cases list no gates"
  );
});

test("a case in only one run is joined as missing on the other side", () => {
  const extra: Run = {
    label: "after",
    slices: [
      ...after.slices,
      {
        label: "after",
        slice: "lint",
        cases: [
          row("lint/0000", {
            verdict: "failed",
            gates: [{ name: "succeeded", passed: false }],
          }),
        ],
      },
    ],
  };
  const { markdown, readmeBlock } = diffRuns(before, extra);

  assert.ok(readmeBlock.includes("| lint | 1 | n/a | 0/1 (0%) |"), readmeBlock);
  assert.ok(
    markdown.includes("| lint/0000 | (not run) | succeeded |"),
    markdown
  );
});

test("the README block between the markers is replaced, and only that block", () => {
  const readme =
    "# Clerk\n\nintro\n\n<!-- eval-diff:start -->\nold table\n<!-- eval-diff:end -->\n\nafter\n";

  assert.equal(
    rewriteReadmeBlock(readme, "| new |"),
    "# Clerk\n\nintro\n\n<!-- eval-diff:start -->\n| new |\n<!-- eval-diff:end -->\n\nafter\n"
  );
  assert.throws(
    () => rewriteReadmeBlock("# no markers\n", "x"),
    /eval-diff:start/
  );
});
